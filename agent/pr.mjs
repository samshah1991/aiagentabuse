// Creates a branch, commits only allowlisted files, and opens a PR with the gh CLI. Never merges.
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathsAllowed } from './guard.mjs';

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts }).trim();
export const LABEL = 'agent-evidence';
export const MAX_OPEN_AGENT_PRS = 2; // stop piling up unreviewed PRs

export function openAgentPrCount() {
  try { return JSON.parse(run('gh', ['pr', 'list', '--label', LABEL, '--state', 'open', '--json', 'number'])).length; } catch { return 0; }
}

export function openPullRequest({ runId, title, body, partial = false }) {
  run('git', ['add', '--', 'data/evidence']);
  const staged = run('git', ['diff', '--cached', '--name-only']).split('\n').filter(Boolean);
  if (!staged.length) return { skipped: 'no changes' };
  if (!pathsAllowed(staged)) { run('git', ['reset']); throw new Error(`refusing to commit non-allowlisted paths: ${staged.join(', ')}`); }
  const branch = `agent/evidence-${runId.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
  run('git', ['checkout', '-b', branch]);
  run('git', ['-c', 'user.name=aiagentabuse-evidence-agent', '-c', 'user.email=evidence-agent@users.noreply.github.com', 'commit', '-m', `${title}\n\nGenerated by the evidence agent. Requires human review before merge.`]);
  run('git', ['push', '-u', 'origin', branch]);
  try { run('gh', ['label', 'create', LABEL, '--color', 'b42318', '--description', 'Machine-generated evidence update: human review required']); } catch { /* label already exists */ }
  const dir = mkdtempSync(join(tmpdir(), 'pr-')); const file = join(dir, 'body.md');
  writeFileSync(file, body);
  const url = run('gh', ['pr', 'create', '--title', partial ? `${title} (partial run)` : title, '--body-file', file, '--label', LABEL]);
  return { branch, url, files: staged };
}
